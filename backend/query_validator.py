"""
backend/query_validator.py
--------------------------
Semantic requirement matching and database validation engine.

Validates that candidate SQL generated by either RuleEngine or Local LLM:
1. Strictly adheres to MySQL 8 syntax and schema constraints (via EXPLAIN dry-run).
2. Faithfully satisfies the natural language requirements (filters, aggregations,
   grouping, ordering, limits, and entity joins).

If any requirement is missing or database error is found, returns structured
diagnostic issues so the LLM Self-Correction Loop can auto-heal the query.
"""

import re
from typing import Tuple, List, Dict, Any, Optional
from backend.database import Database


class QueryValidator:

    def __init__(self, db_instance: Optional[Database] = None):
        self._db = db_instance

    def _get_db(self) -> Database:
        if self._db is None:
            self._db = Database()
        return self._db

    def validate(
        self,
        nl_query: str,
        sql: str,
        tokens: Optional[List[Dict[str, Any]]] = None,
        linked_schema: Optional[Dict[str, Any]] = None
    ) -> Tuple[bool, List[str]]:
        """
        Validates candidate SQL against natural language intent and database schema.

        Returns
        -------
        (is_valid: bool, issues: List[str])
        """
        issues: List[str] = []

        if not sql or not sql.strip():
            return False, ["Empty SQL query provided."]

        cleaned_sql = sql.strip().rstrip(";")
        sql_upper = cleaned_sql.upper()
        nl_lower = nl_query.lower()

        # =====================================================================
        # 1. DATABASE SCHEMA & SYNTAX DRY-RUN (MySQL EXPLAIN)
        # =====================================================================
        try:
            db = self._get_db()
            db.cursor.execute(f"EXPLAIN {cleaned_sql}")
            db.cursor.fetchall()
        except Exception as e:
            err_msg = str(e)
            issues.append(f"MySQL Execution Error: {err_msg}")

        # =====================================================================
        # 2. SEMANTIC REQUIREMENT: LIMIT / TOP N / RANKING
        # =====================================================================
        # Pattern like "top 5", "first 3", "5 most recently", "10 highest"
        limit_match = re.search(r'\b(?:top|first|last|limit)\s+(\d+)\b', nl_lower)
        num_first_match = re.search(r'\b(\d+)\s+(?:most|highest|cheapest|best|top|recent|recently|expensive|lowest)\b', nl_lower)

        expected_limit = None
        if limit_match:
            expected_limit = int(limit_match.group(1))
        elif num_first_match:
            expected_limit = int(num_first_match.group(1))

        if expected_limit is not None:
            if "LIMIT" not in sql_upper:
                issues.append(f"User requested top/first {expected_limit} records, but SQL lacks a LIMIT clause.")
            else:
                # Check if LIMIT number matches
                sql_limit_match = re.search(r'\bLIMIT\s+(\d+)\b', sql_upper)
                if sql_limit_match:
                    found_limit = int(sql_limit_match.group(1))
                    if found_limit != expected_limit:
                        issues.append(f"User requested LIMIT {expected_limit}, but SQL specifies LIMIT {found_limit}.")

        # =====================================================================
        # 3. SEMANTIC REQUIREMENT: ORDERING / SUPERLATIVES
        # =====================================================================
        superlative_patterns = [
            r'\bmost\s+expensive\b', r'\bcostliest\b', r'\bhighest\b',
            r'\bcheapest\b', r'\bleast\b', r'\blowest\b',
            r'\bmost\s+recent\b', r'\blatest\b', r'\boldest\b'
        ]
        has_superlative = any(re.search(pat, nl_lower) for pat in superlative_patterns)
        if has_superlative and "ORDER BY" not in sql_upper:
            # Note: could use MAX/MIN, but if ranking or specific entity requested, ORDER BY is expected
            if not any(agg in sql_upper for agg in ["MAX(", "MIN("]):
                issues.append("User requested superlative ranking (e.g. most/least/highest/cheapest), but SQL lacks an ORDER BY or MAX/MIN clause.")

        # =====================================================================
        # 4. SEMANTIC REQUIREMENT: AGGREGATIONS (COUNT / SUM / AVG / MAX / MIN)
        # =====================================================================
        # Count check
        count_indicators = ["how many", "count of", "number of", "total number of", "how much items"]
        if any(ind in nl_lower for ind in count_indicators) and "COUNT(" not in sql_upper:
            issues.append("User requested a count of items/records, but SQL does not contain COUNT().")

        # Sum / Revenue check
        sum_indicators = ["total revenue", "total amount", "total spending", "sum of", "total sales", "total value"]
        if any(ind in nl_lower for ind in sum_indicators) and "SUM(" not in sql_upper:
            issues.append("User requested total/sum aggregation, but SQL does not contain SUM().")

        # Average check
        avg_indicators = ["average", "avg", "mean"]
        if any(ind in nl_lower for ind in avg_indicators) and "AVG(" not in sql_upper:
            issues.append("User requested average calculation, but SQL does not contain AVG().")

        # =====================================================================
        # 5. SEMANTIC REQUIREMENT: GROUPING (GROUP BY)
        # =====================================================================
        group_indicators = [
            r'\bper\s+(?:category|customer|supplier|warehouse|product|month|year|status|payment)\b',
            r'\beach\s+(?:category|customer|supplier|warehouse|product|month|year|status|payment)\b',
            r'\bby\s+(?:category|customer|supplier|warehouse|status|payment_method|month|year)\b',
            r'\bfor\s+each\b'
        ]
        has_group_intent = any(re.search(pat, nl_lower) for pat in group_indicators)
        if has_group_intent and "GROUP BY" not in sql_upper:
            issues.append("User requested metrics per group/category/entity, but SQL lacks a GROUP BY clause.")

        # =====================================================================
        # 6. SEMANTIC REQUIREMENT: FILTERS & CONDITIONS
        # =====================================================================
        filter_indicators = [
            "greater than", "less than", "more than", "above", "below",
            "higher than", "lower than", "between", "equal to", "named",
            "whose", "out of stock", "never ordered", "status is", "priced at",
            "costing", "in stock"
        ]
        has_filter_intent = any(fi in nl_lower for fi in filter_indicators)

        # Also check for numbers representing condition values (e.g. "warranty is 24 months")
        if tokens:
            has_condition_numbers = any(
                t.get("is_number") for i, t in enumerate(tokens)
                if i == 0 or tokens[i-1].get("lemma") not in ["top", "first", "last", "limit"]
            )
            has_filter_intent = has_filter_intent or has_condition_numbers

        if has_filter_intent and "WHERE" not in sql_upper and "HAVING" not in sql_upper:
            issues.append("User specified filtering conditions/criteria, but SQL contains neither WHERE nor HAVING clause.")

        # Anti-pattern: Aggregate in WHERE clause (e.g., WHERE COUNT(*) > 3)
        if re.search(r'\bWHERE\b[^;]*\b(?:COUNT|SUM|AVG|MAX|MIN)\s*\(', sql_upper):
            issues.append("Invalid SQL logic: Aggregate functions (COUNT, SUM, AVG) cannot be in WHERE clause; use HAVING instead.")

        # Anti-pattern: Column equated to question words, articles, or stopwords
        bogus_match = re.search(r"=\s*'(the|a|an|this|that|these|those|all|any|some|each|every|total|sum|available|which|what|where|who|how|show|find|list|display)'", cleaned_sql, re.IGNORECASE)
        if bogus_match:
            issues.append(f"Invalid condition detected: Column equated to stopword/keyword '{bogus_match.group(1)}'.")

        # Anti-pattern: Numeric column equated to non-numeric string literal (e.g. Quantity = 'abc')
        numeric_cols = ["Quantity", "Selling_Price", "Cost_Price", "Reorder_Level", "Capacity", "Total_Amount", "Unit_Price"]
        for num_col in numeric_cols:
            bad_num_assign = re.search(rf"\b{num_col}\s*=\s*'([a-zA-Z\s]+)'", cleaned_sql, re.IGNORECASE)
            if bad_num_assign:
                issues.append(f"Type mismatch: Numeric column {num_col} cannot be equated to string '{bad_num_assign.group(1)}'.")

        # Specific domain intent: "out of stock"
        if "out of stock" in nl_lower:
            if not ("QUANTITY" in sql_upper or "INVENTORY" in sql_upper):
                issues.append("User requested 'out of stock' items, but SQL does not reference inventory quantity.")

        # Specific domain intent: "never ordered"
        if "never ordered" in nl_lower or "not ordered" in nl_lower:
            if not ("IS NULL" in sql_upper or "NOT EXISTS" in sql_upper or "NOT IN" in sql_upper):
                issues.append("User requested products never ordered, but SQL lacks anti-join or NOT EXISTS / NOT IN logic.")

        # =====================================================================
        # 7. ENTITY & TABLE COVERAGE
        # =====================================================================
        # If user explicitly asked for customer(s) or supplier(s), verify table is referenced
        entity_table_map = {
            "customer": ["customer", "customer_order", "customers"],
            "supplier": ["supplier", "supplier_order", "suppliers"],
            "warehouse": ["warehouse", "warehouses", "inventory"],
            "category": ["category", "categories"],
            "product": ["product", "products", "inventory"]
        }

        for entity, table_names in entity_table_map.items():
            # If user query specifically asks for that entity
            if re.search(rf'\b{entity}s?\b', nl_lower):
                # Check if at least one related table is in the SQL query
                table_found = any(re.search(rf'\b{tbl}\b', cleaned_sql, re.IGNORECASE) for tbl in table_names)
                if not table_found:
                    issues.append(f"User mentioned entity '{entity}', but neither table '{table_names[0]}' nor its relation appears in the SQL query.")

        is_valid = (len(issues) == 0)
        return is_valid, issues
